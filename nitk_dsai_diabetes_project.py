# 27. K-MEANS CLUSTERING AND WCSS
# =============================================================================

print("\nPerforming K-Means clustering...")

# K-Means is unsupervised: target labels are not used for fitting.
# We use a sample to keep execution practical.

cluster_sample_size = min(15000, len(X_train_transformed))

cluster_indices = np.random.choice(
    len(X_train_transformed),
    size=cluster_sample_size,
    replace=False
)

X_cluster = X_train_transformed[cluster_indices]

wcss_values = []

k_values = range(1, 9)

for k in k_values:

    km = MiniBatchKMeans(
        n_clusters=k,
        random_state=RANDOM_STATE,
        batch_size=1024,
        n_init=5
    )

    km.fit(X_cluster)
    wcss_values.append(km.inertia_)

plt.figure(figsize=(8, 5))
plt.plot(
    list(k_values),
    wcss_values,
    marker="o"
)
plt.title("K-Means Elbow Method")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("WCSS / Inertia")
plt.xticks(list(k_values))
plt.tight_layout()
plt.savefig(os.path.join(PLOT_DIR, "17_kmeans_elbow.png"), dpi=150)
plt.show()

