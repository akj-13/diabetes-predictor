print("\nOutlier investigation using the IQR method:")

numeric_investigation = [
    "age",
    "bmi",
    "HbA1c_level",
    "blood_glucose_level"
]

outlier_rows = []

for col in numeric_investigation:

    values = pd.to_numeric(df[col], errors="coerce").dropna()

    q1 = values.quantile(0.25)
    q3 = values.quantile(0.75)
    iqr = q3 - q1

    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr

    outliers = values[
        (values < lower_bound) | (values > upper_bound)
    ]

    outlier_rows.append({
        "Feature": col,
        "Q1": q1,
        "Q3": q3,
        "IQR": iqr,
        "Lower Bound": lower_bound,
        "Upper Bound": upper_bound,
        "Outlier Count": len(outliers),
        "Outlier Percentage": 100 * len(outliers) / len(values)
    })

outlier_report = pd.DataFrame(outlier_rows)
display(outlier_report)

# Important:
# IQR is used to identify potential outliers, not automatically delete them.
# Extreme BMI, glucose or HbA1c values may be genuine observations.
# Removing them without evidence could remove important high-risk cases.


