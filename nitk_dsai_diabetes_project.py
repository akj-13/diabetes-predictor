# =============================================================================
# 10. TRAIN / VALIDATION / TEST SPLIT WITHOUT PROFILE LEAKAGE
# =============================================================================

# First split unique feature profiles, then assign all rows of each profile
# to the same partition.

profile_table = (
    df.groupby("_profile_id", as_index=False)["diabetes"]
    .first()
)

all_groups = profile_table["_profile_id"].values
group_labels = profile_table["diabetes"].values

train_groups, remaining_groups = train_test_split(
    all_groups,
    test_size=TEST_SIZE + VALIDATION_SIZE,
    random_state=RANDOM_STATE,
    stratify=group_labels
)

remaining_label_map = (
    profile_table.set_index("_profile_id")["diabetes"]
)

remaining_labels = np.array([
    remaining_label_map.loc[g] for g in remaining_groups
])

validation_fraction_of_remaining = (
    VALIDATION_SIZE / (TEST_SIZE + VALIDATION_SIZE)
)

validation_groups, test_groups = train_test_split(
    remaining_groups,
    test_size=1 - validation_fraction_of_remaining,
    random_state=RANDOM_STATE,
    stratify=remaining_labels
)

train_df = df[df["_profile_id"].isin(train_groups)].copy()
val_df = df[df["_profile_id"].isin(validation_groups)].copy()
test_df = df[df["_profile_id"].isin(test_groups)].copy()

# Confirm that no identical feature profile crosses partitions.
assert set(train_groups).isdisjoint(set(validation_groups))
assert set(train_groups).isdisjoint(set(test_groups))
assert set(validation_groups).isdisjoint(set(test_groups))

X_train = train_df[FEATURE_COLUMNS].copy()
y_train = train_df["diabetes"].copy()

